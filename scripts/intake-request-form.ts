export const INTAKE_REQUEST_TITLE = "שאלון העסקה";
export const intakeRequestForm: FormDefinition = { schemaVersion: 1, title: INTAKE_REQUEST_TITLE, pages, settings: { layout: "wizard", submitLabel: "שליחה" } };

async function main() {
  const parsed = parseFormDefinition(intakeRequestForm);
  if (!parsed.success) throw new Error(JSON.stringify(parsed.error.issues, null, 1));
  const issues = publishIssues(intakeRequestForm);
  if (issues.length) throw new Error(issues.map((i) => i.message).join("\n"));
  if (!process.argv.includes("--create")) {
    console.log(JSON.stringify(intakeRequestForm, null, 2));
    return;
  }
  const { createTemplate } = await import("../src/server/forms-store");
  console.log(await createTemplate(INTAKE_REQUEST_TITLE, intakeRequestForm, "web"));
}

if (process.argv[1]?.includes("intake-request-form")) main().catch((e) => { console.error(e); process.exit(1); });
